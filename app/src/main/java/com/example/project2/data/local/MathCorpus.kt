    fun getRandomSpyWord(courseLevel: Int, difficulty: Int = 1): SpyWord {
        val safeCourse = courseLevel.coerceIn(0, 4)
        val safeDiff = difficulty.coerceIn(0, 2)

        val exactPool = SPY_WORDS.filter { it.courseLevel == safeCourse && it.difficultyLevel == safeDiff }
        if (exactPool.isNotEmpty()) return exactPool.random()

        val coursePool = SPY_WORDS.filter { it.courseLevel == safeCourse }
        if (coursePool.isNotEmpty()) return coursePool.random()

        val diffPool = SPY_WORDS.filter { it.difficultyLevel == safeDiff }
        if (diffPool.isNotEmpty()) return diffPool.random()

        return SPY_WORDS.random()
    }

    fun getRandomSpyWord(levelIndex: Int): SpyWord {
        val safeLevel = levelIndex.coerceIn(0, 4)
        val pool = SPY_WORDS.filter { it.courseLevel == safeLevel || it.difficultyLevel == safeLevel }
        return pool.randomOrNull() ?: SPY_WORDS.random()
    }

    fun getRandomForeheadCards(category: ForeheadCategory, count: Int = 20): List<ForeheadCard> {
        val pool = FOREHEAD_CARDS.filter { it.category == category }
        return pool.shuffled().take(count)
    }

